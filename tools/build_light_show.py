"""Build the protected Light Show with the shared kit and the author's ID8 RHMI layout."""
from pathlib import Path
import argparse,json,os,shutil,sys,tempfile
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools/protected-apps/kit/tools'))
import build as kit


def inside(path, base):
    return os.path.commonpath([str(Path(path).resolve()),str(Path(base).resolve())])==str(Path(base).resolve())


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('app',nargs='?',default='light_show')
    parser.add_argument('--preview-only',action='store_true')
    parser.add_argument('--sdk',default=str(ROOT/'oap-sdk'))
    parser.add_argument('--dist')
    args=parser.parse_args()
    if not args.app.startswith('light_show') or not args.app.replace('_','').isalnum():raise ValueError('Unexpected app id')
    mode='preview'
    if not args.preview_only:
        sdk=kit.check_sdk(args.sdk)
        mode='placeholder' if sdk.get('mguPlaceholder') is True else 'real'
    dist=Path(args.dist or (kit.PREVIEW_DIST if args.preview_only else kit.DIST)).resolve()
    dist.mkdir(parents=True,exist_ok=True)
    temporary=Path(tempfile.mkdtemp(prefix='.light-show-build-',dir=str(dist)))
    assert inside(temporary,dist)
    try:
        mtime=kit.source_date_epoch()
        kit.build(args.app,'ru',dist=str(temporary),sdk=args.sdk,mode=mode,mtime=mtime)
        stage=temporary/args.app;source=stage/'source';rhmi=source/'rhmiData'
        # Light Show draws its own full header. This app's staged Display uses
        # the shared native pixmap/target protocol without drawing a second kit
        # header. No runtime file for another app is changed.
        display_file=source/'javascript/kit/display.js'
        display=display_file.read_text('utf8')
        changes={
            "const native = this.screen.chrome !== false && process.env.MGU_RENDERD_PROTO !== 'upstream';":
            "const native = (this.screen.chrome !== false || this.spec.id === "+repr(args.app)+") && process.env.MGU_RENDERD_PROTO !== 'upstream';",
            "if (!this.screen || this.screen.chrome === false) return false;":
            "if (!this.screen || (this.screen.chrome === false && this.spec.id !== "+repr(args.app)+")) return false;",
        }
        for before,after in changes.items():
            if display.count(before)!=1:raise ValueError('Shared Display changed; review Light Show native integration')
            display=display.replace(before,after)
        display_file.write_text(display,encoding='utf8')
        package=json.loads((source/'package.json').read_text('utf8'))
        package.update(private=True,mguLocalOnly=True,mguInternet=True,mguHmi=['ID7','ID8'],requires={'mgu-deploy':'0.7.5'})
        (source/'package.json').write_text(json.dumps(package,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
        shutil.copyfile(ROOT/'apps'/args.app/'preview-font.json',source/'javascript/kit/fonts/light_show-preview.json')
        # The source 0.4.1 ID8 XML uses Wide_List states, components without
        # ID7 widget names, and the Bar buttons moved into the List. Preserve
        # that transformation against the IDs generated by the current kit.
        xml=ET.parse(rhmi/'uiDescriptions/ID7/application.xml')
        for state in xml.getroot().findall('container'):
            if state.get('type')=='state':state.set('widget','LT_State_Wide_List')
            groups=state.findall('layoutGroup')
            listing=next((g for g in groups if g.get('name')=='List'),None)
            for bar in [g for g in groups if g.get('name')=='Bar']:
                if listing is None:raise ValueError('ID8 list layout missing')
                for component in list(bar):listing.append(component)
                state.remove(bar)
        for component in xml.getroot().iter('component'):component.attrib.pop('widget',None)
        id8=rhmi/'uiDescriptions/ID8';id8.mkdir()
        xml.write(id8/'application.xml',encoding='utf-8',xml_declaration=True)
        shutil.copyfile(rhmi/'uiDescriptions/ID7/uiDescription.json',id8/'uiDescription.json')
        meta=json.loads((rhmi/'application.json').read_text('utf8'))
        meta['application']['uiDescriptions'].append({'applicationFilePath':'./uiDescriptions/ID8/application.xml','uiDescriptionFilePath':'./uiDescriptions/ID8/uiDescription.json','hmi':['ID8']})
        for group in meta['application']['variantGroups']:group['hmi']=['ID7','ID8']
        (rhmi/'application.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
        version=package['version'];suffix='.preview' if mode=='preview' else '-NOT-INSTALLABLE' if mode=='placeholder' else ''
        artifact=dist/(args.app+'@'+version+suffix+'.tgz')
        packed=temporary/'protected.tgz'
        kit.write_archive(str(packed),[(str(source),'package')],mtime)
        final=dist/args.app
        assert final.resolve().parent==dist
        kit.replace_dir(str(stage),str(final))
        os.replace(packed,artifact)
        print('Light Show protected '+version+': '+str(artifact)+(' (TEST ONLY, no real SDK)' if mode!='real' else ''))
    finally:
        assert inside(temporary,dist)
        shutil.rmtree(temporary)


if __name__=='__main__':main()
